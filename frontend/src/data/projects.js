// Decorate every project with an aesthetic. The visible chip on a tile is
// now the aesthetic label (Atelier, Editorial, Cinematic, …), not the
// industry. The original industry is preserved in `industry` for SEO copy
// and structured data; `tag` becomes the aesthetic label.
const _DECORATED = _PROJECTS.map((p) => {
  const aesthetic = inferAesthetic({ tag: p.tag, slug: p.slug, aesthetic: p.aesthetic });
  return {
    ...p,
    industry: p.industry || p.tag,   // preserve original
    aesthetic: aesthetic.slug,
    aestheticLabel: aesthetic.label,
    tag: aesthetic.label,            // displayed chip = aesthetic label
  };
});

export const PROJECTS = sortByAesthetic(_DECORATED);

// Filter chips are now driven by aesthetics. The kind-based chips
// (Recently Live, Experimentation, Demo Portfolio) stay — they're a
// useful orthogonal cut.
export const FILTER_CHIPS = [
  { id: "all", label: "All" },
  { id: "recently-live", label: "Recently Live" },
  { id: "experimentation", label: "Experimentation" },
  { id: "demo", label: "Demo Portfolio" },
  ...AESTHETIC_LIST.map((a) => ({ id: a.label, label: a.label })),
];

export function filterProjects(projects, filter) {
  if (filter === "all") return projects;
  if (filter === "recently-live") return projects.filter((p) => p.kind === "recently-live");
  if (filter === "experimentation") return projects.filter((p) => p.kind === "experimentation");
  if (filter === "demo") return projects.filter((p) => p.kind === "demo");
  // Aesthetic filter — `tag` is the aesthetic label after decoration.
  return projects.filter((p) => p.tag === filter);
}

export function findProject(slug) {
  return PROJECTS.find((p) => p.slug === slug);
}

export function adjacentProjects(slug) {
  const idx = PROJECTS.findIndex((p) => p.slug === slug);
  if (idx < 0) return { prev: null, next: null };
  const prev = PROJECTS[(idx - 1 + PROJECTS.length) % PROJECTS.length];
  const next = PROJECTS[(idx + 1) % PROJECTS.length];
  return { prev, next };
}
